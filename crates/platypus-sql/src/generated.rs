//! The columns a table fills by itself: numbered (serials, identities, `AUTO_INCREMENT`,
//! SQLite's rowid) and computed (generated columns, SQL Server's `rowversion`). The data
//! editor leaves them to the database: a duplicated row gets a new number, a computed column
//! is never written, and the undo script puts numbers back with the override the database
//! asks for (see [`crate::dml::restore_inserts`]).

use platypus_core::{Connection, Result, TextRow, TextRowExt, query_text};

use crate::Dialect;

/// How the database fills a column by itself.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Generated {
    /// Numbered when left out, and takes the values given: serials, `GENERATED BY DEFAULT AS
    /// IDENTITY`, MySQL's `AUTO_INCREMENT`, SQLite's rowid.
    Numbered,
    /// Numbered, and takes a value only with an override: PostgreSQL's `GENERATED ALWAYS AS
    /// IDENTITY`, SQL Server's `IDENTITY`. It cannot be changed either.
    Identity,
    /// Computed by the database and never written: generated and computed columns, SQL
    /// Server's `rowversion`.
    Computed,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedColumn {
    pub name: String,
    pub generated: Generated,
}

/// The catalog query of the columns of `schema.table` and how each is filled; `None` where
/// the dialect has no such columns, or they are not read.
#[must_use]
pub fn query(dialect: Dialect, schema: &str, table: &str) -> Option<String> {
    let (s, t) = (dialect.quote_literal(schema), dialect.quote_literal(table));
    Some(match dialect {
        Dialect::Postgres => format!(
            "SELECT a.attname, a.attidentity::text, a.attgenerated::text,
                    pg_get_expr(d.adbin, d.adrelid)
             FROM pg_attribute a
             LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
             WHERE a.attrelid = (SELECT c.oid FROM pg_class c
                                 JOIN pg_namespace n ON n.oid = c.relnamespace
                                 WHERE n.nspname = {s} AND c.relname = {t})
               AND a.attnum > 0 AND NOT a.attisdropped"
        ),
        Dialect::MySql => format!(
            "SELECT COLUMN_NAME, EXTRA FROM information_schema.COLUMNS
             WHERE TABLE_SCHEMA = {s} AND TABLE_NAME = {t}"
        ),
        Dialect::SqlServer => {
            let object = dialect.quote_literal(&dialect.qualified(Some(schema), table));
            format!(
                "SELECT c.name, CAST(c.is_identity AS int), CAST(c.is_computed AS int),
                        CASE WHEN c.system_type_id = 189 THEN 1 ELSE 0 END
                 FROM sys.columns c WHERE c.object_id = OBJECT_ID({object})"
            )
        }
        // `hidden` is 2 or 3 for generated columns. A single `INTEGER PRIMARY KEY` column is
        // the rowid, unless the table is `WITHOUT ROWID`.
        Dialect::Sqlite => format!(
            "SELECT x.name, x.type, x.pk, x.hidden,
                    (SELECT count(*) FROM pragma_table_info({t}, {s}) WHERE pk > 0),
                    (SELECT sql FROM {}.sqlite_master WHERE type = 'table' AND name = {t})
             FROM pragma_table_xinfo({t}, {s}) x",
            dialect.quote_ident(schema)
        ),
        // Virtual columns, and identities (12c): `ALWAYS` takes no value, `BY DEFAULT` does.
        Dialect::Oracle => format!(
            "SELECT c.COLUMN_NAME, c.VIRTUAL_COLUMN, i.GENERATION_TYPE
             FROM ALL_TAB_COLS c
             LEFT JOIN ALL_TAB_IDENTITY_COLS i ON i.OWNER = c.OWNER
               AND i.TABLE_NAME = c.TABLE_NAME AND i.COLUMN_NAME = c.COLUMN_NAME
             WHERE c.OWNER = {s} AND c.TABLE_NAME = {t} AND c.HIDDEN_COLUMN = 'NO'"
        ),
        _ => return None,
    })
}

/// How a column of a row of [`query`] is filled; `None` when it is written as given.
fn generated(dialect: Dialect, row: &TextRow) -> Option<Generated> {
    match dialect {
        Dialect::Postgres => {
            let default = row.opt(3).unwrap_or_default();
            if !row.text(2).is_empty() {
                Some(Generated::Computed)
            } else if row.text(1) == "a" {
                Some(Generated::Identity)
            } else if row.text(1) == "d" || default.starts_with("nextval(") {
                Some(Generated::Numbered)
            } else {
                None
            }
        }
        Dialect::MySql => {
            // `DEFAULT_GENERATED` marks a default expression, `VIRTUAL GENERATED` and `STORED
            // GENERATED` (MariaDB also `PERSISTENT GENERATED`) a generated column.
            let extra = row.text(1).to_ascii_lowercase();
            if extra.contains("auto_increment") {
                Some(Generated::Numbered)
            } else if extra.split_whitespace().any(|w| w == "generated") {
                Some(Generated::Computed)
            } else {
                None
            }
        }
        Dialect::SqlServer => {
            if row.text(2) == "1" || row.text(3) == "1" {
                Some(Generated::Computed)
            } else if row.text(1) == "1" {
                Some(Generated::Identity)
            } else {
                None
            }
        }
        Dialect::Sqlite => {
            let sql = row.text(5).to_ascii_uppercase();
            let without_rowid = sql
                .split_whitespace()
                .collect::<Vec<_>>()
                .windows(2)
                .any(|w| w == ["WITHOUT", "ROWID"]);
            if matches!(row.text(3).as_str(), "2" | "3") {
                Some(Generated::Computed)
            } else if row.text(2) == "1"
                && row.text(4) == "1"
                && row.text(1).eq_ignore_ascii_case("integer")
                && !without_rowid
            {
                Some(Generated::Numbered)
            } else {
                None
            }
        }
        Dialect::Oracle => match (row.text(1).as_str(), row.text(2).as_str()) {
            ("YES", _) => Some(Generated::Computed),
            (_, "ALWAYS") => Some(Generated::Identity),
            (_, t) if t.starts_with("BY DEFAULT") => Some(Generated::Numbered),
            _ => None,
        },
        _ => None,
    }
}

/// The columns of the rows of [`query`] the database fills by itself.
#[must_use]
pub fn from_rows(dialect: Dialect, rows: &[TextRow]) -> Vec<GeneratedColumn> {
    rows.iter()
        .filter_map(|row| {
            generated(dialect, row).map(|generated| GeneratedColumn {
                name: row.text(0),
                generated,
            })
        })
        .collect()
}

/// The columns of `schema.table` the database fills by itself; empty where they are not read.
///
/// # Errors
///
/// When the catalog query fails, e.g. on an old server.
pub async fn generated_columns(
    conn: &dyn Connection,
    dialect: Dialect,
    schema: &str,
    table: &str,
) -> Result<Vec<GeneratedColumn>> {
    let Some(sql) = query(dialect, schema, table) else {
        return Ok(Vec::new());
    };
    Ok(from_rows(dialect, &query_text(conn, &sql).await?))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn row(cells: &[Option<&str>]) -> TextRow {
        cells.iter().map(|c| c.map(str::to_owned)).collect()
    }

    fn kinds(dialect: Dialect, rows: &[TextRow]) -> Vec<(String, Generated)> {
        from_rows(dialect, rows)
            .into_iter()
            .map(|c| (c.name, c.generated))
            .collect()
    }

    #[test]
    fn reads_postgres_identities_serials_and_generated_columns() {
        let rows = [
            row(&[Some("id"), Some("a"), Some(""), None]),
            row(&[Some("n"), Some("d"), Some(""), None]),
            row(&[
                Some("s"),
                Some(""),
                Some(""),
                Some("nextval('t_s_seq'::regclass)"),
            ]),
            row(&[Some("total"), Some(""), Some("s"), Some("(a * 2)")]),
            row(&[Some("plain"), Some(""), Some(""), Some("0")]),
        ];
        assert_eq!(
            kinds(Dialect::Postgres, &rows),
            [
                ("id".to_owned(), Generated::Identity),
                ("n".to_owned(), Generated::Numbered),
                ("s".to_owned(), Generated::Numbered),
                ("total".to_owned(), Generated::Computed),
            ]
        );
    }

    #[test]
    fn reads_oracle_identities_and_virtual_columns() {
        let rows = [
            row(&[Some("ID"), Some("NO"), Some("ALWAYS")]),
            row(&[Some("N"), Some("NO"), Some("BY DEFAULT ON NULL")]),
            row(&[Some("TWICE"), Some("YES"), None]),
            row(&[Some("A"), Some("NO"), None]),
        ];
        assert_eq!(
            kinds(Dialect::Oracle, &rows),
            [
                ("ID".to_owned(), Generated::Identity),
                ("N".to_owned(), Generated::Numbered),
                ("TWICE".to_owned(), Generated::Computed),
            ]
        );
        assert!(
            query(Dialect::Oracle, "HR", "T")
                .unwrap()
                .contains("ALL_TAB_IDENTITY_COLS")
        );
    }

    #[test]
    fn reads_mysql_auto_increment_and_generated_columns() {
        let rows = [
            row(&[Some("id"), Some("auto_increment")]),
            row(&[Some("v"), Some("VIRTUAL GENERATED")]),
            row(&[Some("s"), Some("STORED GENERATED")]),
            row(&[Some("p"), Some("PERSISTENT GENERATED")]),
            row(&[
                Some("at"),
                Some("DEFAULT_GENERATED on update CURRENT_TIMESTAMP"),
            ]),
            row(&[Some("x"), Some("")]),
        ];
        assert_eq!(
            kinds(Dialect::MySql, &rows),
            [
                ("id".to_owned(), Generated::Numbered),
                ("v".to_owned(), Generated::Computed),
                ("s".to_owned(), Generated::Computed),
                ("p".to_owned(), Generated::Computed),
            ]
        );
    }

    #[test]
    fn reads_sql_server_identity_computed_and_rowversion_columns() {
        let rows = [
            row(&[Some("id"), Some("1"), Some("0"), Some("0")]),
            row(&[Some("c"), Some("0"), Some("1"), Some("0")]),
            row(&[Some("rv"), Some("0"), Some("0"), Some("1")]),
            row(&[Some("x"), Some("0"), Some("0"), Some("0")]),
        ];
        assert_eq!(
            kinds(Dialect::SqlServer, &rows),
            [
                ("id".to_owned(), Generated::Identity),
                ("c".to_owned(), Generated::Computed),
                ("rv".to_owned(), Generated::Computed),
            ]
        );
    }

    #[test]
    fn reads_the_sqlite_rowid_and_generated_columns() {
        let table = "CREATE TABLE t (id INTEGER PRIMARY KEY, a, b AS (a * 2))";
        let rows = [
            row(&[
                Some("id"),
                Some("INTEGER"),
                Some("1"),
                Some("0"),
                Some("1"),
                Some(table),
            ]),
            row(&[
                Some("a"),
                Some(""),
                Some("0"),
                Some("0"),
                Some("1"),
                Some(table),
            ]),
            row(&[
                Some("b"),
                Some(""),
                Some("0"),
                Some("2"),
                Some("1"),
                Some(table),
            ]),
        ];
        assert_eq!(
            kinds(Dialect::Sqlite, &rows),
            [
                ("id".to_owned(), Generated::Numbered),
                ("b".to_owned(), Generated::Computed),
            ]
        );
        // Not the rowid: `INT`, a key of two columns, a table without rowid.
        let cases = [
            ("INT", "1", table),
            ("INTEGER", "2", table),
            (
                "INTEGER",
                "1",
                "CREATE TABLE t (id INTEGER PRIMARY KEY) without\n  rowid",
            ),
        ];
        for (declared, keys, sql) in cases {
            let rows = [row(&[
                Some("id"),
                Some(declared),
                Some("1"),
                Some("0"),
                Some(keys),
                Some(sql),
            ])];
            assert_eq!(kinds(Dialect::Sqlite, &rows), [], "{declared} {keys} {sql}");
        }
    }

    #[test]
    fn has_no_query_where_columns_are_not_read() {
        assert!(query(Dialect::ClickHouse, "db", "t").is_none());
        assert!(
            query(Dialect::SqlServer, "dbo", "it's")
                .unwrap()
                .contains("OBJECT_ID(N'dbo.[it''s]')")
        );
    }
}
