// Regression guard (passes): editing Oracle rows in the data grid. On a table with an identity
// key, text, NUMBER(10,2) and a quoted mixed-case name: a changed cell, a deleted row and a new
// row (identity left to the database) are saved in one go; a mass "Set value…" on a column is
// saved; the table without a key is read-only.
import { CTRL, assert, button, connectOracle, dropAll, editBar, focusCell, grid, gridMenu, needsOracle, openData, ora, oracleSetup, previewSql, save, setCell, visibleTab } from "../qa-ora.mjs";

export const skip = needsOracle();
const T = "QA_ORA_GE Mixed";

export function setup({ dir }) {
  oracleSetup(dir);
  dropAll(`TABLE "${T}"`, "TABLE QA_ORA_GE_NOKEY");
  ora(`CREATE TABLE "${T}" ("Id" NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 10) PRIMARY KEY, "Name" VARCHAR2(30 CHAR), PRICE NUMBER(10,2));
INSERT INTO "${T}" ("Id", "Name", PRICE) VALUES (1, 'a', 1.5);
INSERT INTO "${T}" ("Id", "Name", PRICE) VALUES (2, 'b', 2.5);
CREATE TABLE QA_ORA_GE_NOKEY (A NUMBER, B VARCHAR2(5));
INSERT INTO QA_ORA_GE_NOKEY VALUES (1, 'x');
COMMIT;`);
}

export default async function (page) {
  try {
    await connectOracle(page);
    await openData(page, T);
    await page.waitFor(`${editBar}.includes("to edit a cell")`, 15_000);
    await focusCell(page, 0, 1);
    await setCell(page, "àé 'q' 😀");
    await focusCell(page, 1, 2);
    await page.key("Delete", "Delete", 46);
    await page.key("Insert", "Insert", 45);
    await page.waitFor(`${editBar}.includes("3 rows changed")`);
    // The new row keeps the focused column (PRICE); Enter moves down a row.
    await setCell(page, "7.25");
    await page.key("ArrowUp", "ArrowUp", 38);
    await page.key("ArrowLeft", "ArrowLeft", 37);
    await setCell(page, "new");
    const sql = await previewSql(page);
    assert.match(sql, /INSERT INTO PLATYPUS\."QA_ORA_GE Mixed" \(PRICE, "Name"\) VALUES \(7\.25, 'new'\)/, sql);
    const out = await save(page);
    assert.doesNotMatch(out, /ERROR/, out);
    assert.equal(ora(`SELECT LISTAGG("Id" || ':' || "Name" || ':' || PRICE, ',') WITHIN GROUP (ORDER BY "Id") FROM "${T}";`), "1:àé 'q' 😀:1.5,10:new:7.25");

    // Mass edit.
    await page.eval(`${grid}.focus()`);
    await focusCell(page, 0, 2);
    await page.key("ArrowDown", "ArrowDown", 40, 8);
    await gridMenu(page, "Edit selection", "Set value…");
    await page.waitFor(`document.querySelector('.mass-edit') !== null`);
    await page.eval(`(() => {
      const el = document.querySelectorAll('.mass-edit input:not([type])')[0];
      Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, '99.99');
      el.dispatchEvent(new Event('input', { bubbles: true }));
    })()`);
    await page.eval(`${button("document.querySelector('.mass-edit')", "Apply")}.click()`);
    await page.waitFor(`${editBar}.includes("rows changed")`, 15_000);
    const mass = await save(page);
    assert.doesNotMatch(mass, /ERROR/, mass);
    assert.equal(ora(`SELECT LISTAGG(PRICE, ',') WITHIN GROUP (ORDER BY "Id") FROM "${T}";`), "99.99,99.99");

    await page.key("w", "KeyW", 87, CTRL);
    await openData(page, "QA_ORA_GE_NOKEY");
    await page.waitFor(`/Read-only/.test(${editBar})`, 15_000);
    assert.match(await page.eval(editBar), /Read-only/i);
    assert.ok(await page.eval(`${visibleTab} != null`));
  } finally {
    dropAll(`TABLE "${T}"`, "TABLE QA_ORA_GE_NOKEY");
  }
}
