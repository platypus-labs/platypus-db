// SCH-05 (high). Compare with… is offered on Oracle but its script is not Oracle SQL, and two
// identical schemas are never "the same":
//  - an identity column is copied as DEFAULT "QA3S_SRC"."ISEQ$$_74503".nextval (the source
//    user's hidden sequence), and set with ALTER TABLE … ALTER COLUMN … SET DEFAULT (ORA-01735);
//  - unnamed constraints are matched by their system names (SYS_C008984), which differ between
//    two users, so identical tables get ADD CONSTRAINT SYS_C… UNIQUE again;
//  - a changed column becomes ALTER COLUMN … TYPE … USING x::VARCHAR2(100), a new one
//    ADD COLUMN (Oracle: MODIFY / ADD (…)); a new table gets NOT NULL before DEFAULT (ORA-03076);
//  - the script is wrapped in BEGIN; … COMMIT;, which the editor runs as one PL/SQL block:
//    Script reports no error and nothing changes.
// Steps: users QA3S_SRC and QA3S_DST with the same table items (identity id, unique code);
// navigator > QA3S_SRC > Compare with… > QA3 Oracle dst · QA3S_DST > Compare. Then change a
// column type and drop a column in QA3S_DST, compare, run the script, compare again.
// Expected: "nothing to change" for identical schemas; an Oracle script that runs and leaves
// nothing to change. (Or no Compare with… on Oracle, if it is not supported.)
// Actual: a script for identical schemas; the scripts fail with ORA-01735 / ORA-03076.
// Suspected: crates/platypus-schema/src/ddl.rs (no Oracle branch for ALTER COLUMN, ADD, column
// order of DEFAULT / NOT NULL), the Oracle design read (identity, system-named constraints) and
// apps/desktop/src/schema/actions.ts:25 (offered for every driver but Mongo).
import assert from "node:assert/strict";
import { DST, ENGINES, SRC, compareUi, needsEngines, openPath, roundTrip, saveEngines, told } from "../schema-compare-helpers.mjs";

export const skip = needsEngines("oracle");
const TABLE = `CREATE TABLE items (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code VARCHAR2(20) NOT NULL UNIQUE, name VARCHAR2(100) DEFAULT 'none', qty NUMBER(10));`;

export function setup({ dir }) {
  ENGINES.oracle.seed(dir, SRC, TABLE);
  ENGINES.oracle.seed(dir, DST, TABLE);
  saveEngines(dir, ["oracle"]);
}

export default async function (page) {
  const problems = [];
  try {
    await openPath(page, ["QA3 Oracle src", "QA3S_SRC"], 90_000);
    const identical = await compareUi(page, ["QA3 Oracle src"], "QA3S_SRC", "QA3 Oracle dst", "QA3S_DST", 90_000);
    if (identical.same !== true) problems.push(`identical schemas get a script:\n${identical.sql ?? identical.error}`);
    ENGINES.oracle.exec(null, DST, `ALTER TABLE items MODIFY name VARCHAR2(50);\nALTER TABLE items DROP COLUMN qty;`);
    const r = await roundTrip(page, ["QA3 Oracle src"], "QA3S_SRC", "QA3 Oracle dst", "QA3S_DST");
    if (!r.sql) problems.push(`no script for a changed table: ${told(r)}`);
    else if (r.runError !== null) problems.push(`the script fails: ${r.runError}\n${r.sql}`);
    else if (r.second.same !== true) problems.push(`a second comparison still finds changes: ${told(r)}`);
  } finally {
    // The app's sessions may still be ending: the next setup drops the users otherwise.
    for (const u of [SRC, DST]) {
      try {
        ENGINES.oracle.drop(u);
      } catch {}
    }
  }
  assert.deepEqual(problems, []);
}
